async function updateArticles() {
  console.log("Starting Article Sync (Part 2)...");
  for (const article of articles) {
    try {
      await db.article.upsert({
        where: { slug: article.slug },
        update: {
          title: article.title,
          excerpt: article.excerpt,
          content: article.content,
          category: article.category,
          tags: article.tags,
          seoTitle: article.seoTitle,
          seoDescription: article.seoDescription,
          updatedAt: new Date()
        },
        create: {
          title: article.title,
          slug: article.slug,
          excerpt: article.excerpt,
          content: article.content,
          category: article.category,
          tags: article.tags,
          seoTitle: article.seoTitle,
          seoDescription: article.seoDescription,
          readingMinutes: Math.ceil(article.content.split(' ').length / 200),
          published: true,
          featured: false
        }
      });
      console.log("✅ Upserted article: " + article.slug);
    } catch (e) {
      console.error("❌ Failed to upsert article " + article.slug, e);
    }
  }
  console.log("Done Part 2.");
}

