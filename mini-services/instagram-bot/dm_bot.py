def generate_dm_reply(message_text: str) -> str:
    text = message_text.lower()
    
    if any(word in text for word in ["قیمت", "چنده", "هزینه"]):
        return "سلام! 🌸 برای دیدن قیمت‌های بروز و شگفت‌انگیز ما به سایت liceno.ir سر بزنید. با کد تخفیف INSTA10 می‌تونید 10٪ تخفیف بگیرید! 🎉"
        
    if any(word in text for word in ["خرید", "سفارش", "تهیه"]):
        return "سلام دوست عزیز! 🛍️ برای خرید سریع و تحویل آنی به وبسایت ما مراجعه کنید: liceno.ir. فراموش نکنید از کد تخفیف INSTA10 استفاده کنید! ✨"
        
    if any(word in text for word in ["تخفیف", "کد"]):
        return "سلام! 🎁 بله، برای فالوورهای عزیزمون کد تخفیف اختصاصی داریم: INSTA10 رو در سایت liceno.ir وارد کنید و لذت ببرید! 🎊"
        
    if any(word in text for word in ["پشتیبانی", "خرابی", "مشکل", "کار نمیکنه"]):
        return "سلام وقت بخیر! 🛠️ همکاران ما در بخش پشتیبانی سایت در اسرع وقت مشکل شما رو حل می‌کنن. لطفا وارد سایت liceno.ir بشید و به پشتیبانی تیکت/پیام بدید. 🙏"
        
    # Default fallback
    return "سلام! 🌟 ممنون از پیام شما. برای اطلاعات بیشتر و خرید محصولات، به سایت ما liceno.ir مراجعه کنید. در صورت نیاز به راهنمایی بیشتر، پشتیبانی سایت در خدمت شماست."
